/**
 * Which Bot API methods the simulator answers: compares the methods of
 * `TelegramSimulator` with every method grammY's types know
 * (`@grammyjs/types/methods.d.ts`) and writes docs/bot-api-coverage.md.
 *
 *   bun run api-coverage
 *
 * test/api-coverage.test.ts fails when the page is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { TelegramSimulator } from '../packages/simulator/src';

const root = join(import.meta.dir, '..');
export const COVERAGE_PAGE = join(root, 'docs/bot-api-coverage.md');

/** Every Bot API method, from grammY's types. */
export function botApiMethods(): string[] {
  const types = dirname(createRequire(join(root, 'package.json')).resolve('@grammyjs/types/package.json'));
  const source = readFileSync(join(types, 'methods.d.ts'), 'utf8');
  return [...new Set([...source.matchAll(/^ {4}([a-zA-Z]+)\(/gm)].map((m) => m[1]!))].sort();
}

/** The methods the simulator answers. */
export function simulatorMethods(): string[] {
  const sim = new TelegramSimulator();
  return Object.keys((sim as unknown as { methods: Record<string, unknown> }).methods).sort();
}

/** Areas of supported methods, first match wins. */
const AREAS: [string, (m: string) => boolean][] = [
  ['Getting updates and the bot', (m) => /^(getUpdates|setWebhook|deleteWebhook|getWebhookInfo|getMe|logOut|close)$/.test(m)],
  ['Payments', (m) => /Invoice|Shipping|PreCheckout|StarPayment/.test(m)],
  ['Forum topics', (m) => /ForumTopic/.test(m)],
  ['Invite links and join requests', (m) => /InviteLink|JoinRequest/.test(m)],
  ['Reactions', (m) => /Reaction/.test(m)],
  ['Stickers', (m) => /Sticker/.test(m)],
  ['Sending messages', (m) => /^(send|copy|forward)/.test(m)],
  ['Editing and deleting messages', (m) => /^(edit|delete|stop)\w*(Message|Poll|LiveLocation)/.test(m) || /^deleteMessages$/.test(m)],
  ['Answering queries', (m) => /^(answer|savePrepared)/.test(m)],
  ['Bot settings', (m) => /My|MenuButton/.test(m)],
  ['Chats and members', (m) => /Chat|Member|pin|Boost/.test(m)],
  ['Files', () => true],
];

/** Methods the simulator doesn't plan to answer: a UI library doesn't need them. */
const NOT_PLANNED: [string, string, RegExp][] = [
  // First match wins: business-account gifts and stars are business methods.
  ['Business accounts', 'Bots acting for a Telegram Business account.', /Business/],
  ['Stars, gifts, paid media, games, checklists and stories', 'Telegram-side economies and content a bot UI library does not draw.', /Star|Gift|Premium|PaidMedia|Game|Checklist|Story/],
  ['Sticker sets', 'Creating and editing sticker sets is account management, not UI.', /Sticker/],
  ['Managed bots', 'Bots that manage other bots.', /ManagedBot/],
  ['Verification', 'Verifying users and chats on behalf of an organization.', /[vV]erif/],
  ['Passport', 'Telegram Passport data.', /Passport/],
  [
    'Profiles, channel posts and guests',
    "The bot's own profile, users' emoji status and profile media, live photos, suggested channel posts and guest queries: account features, not screens a bot draws.",
    /^(setMyProfilePhoto|removeMyProfilePhoto|setUserEmojiStatus|getUserProfileAudios|sendLivePhoto|approveSuggestedPost|declineSuggestedPost|answerGuestQuery|getUserPersonalChatMessages)$/,
  ],
];

function list(methods: string[]) {
  return methods.map((m) => `\`${m}\``).join(', ');
}

/** The coverage page, as Markdown. */
export function apiCoverage(): string {
  const all = botApiMethods();
  const supported = new Set(simulatorMethods());
  const unsupported = all.filter((m) => !supported.has(m));
  const areas = new Map<string, string[]>(AREAS.map(([name]) => [name, []]));
  for (const method of all.filter((m) => supported.has(m))) areas.get(AREAS.find(([, test]) => test(method))![0])!.push(method);
  const notPlanned = new Map<string, string[]>(NOT_PLANNED.map(([name]) => [name, []]));
  const planned: string[] = [];
  for (const method of unsupported) {
    const group = NOT_PLANNED.find(([, , pattern]) => pattern.test(method));
    if (group) notPlanned.get(group[0])!.push(method);
    else planned.push(method);
  }

  const lines = [
    '# Bot API coverage',
    '',
    '<!-- Generated by scripts/api-coverage.ts: run `bun run api-coverage`, do not edit by hand. -->',
    '',
    'Which Bot API methods the [simulator](simulator.md) answers. The page is',
    'generated by `bun run api-coverage` (`scripts/api-coverage.ts`), which',
    "compares the simulator's methods with every method in grammY's types",
    '(`@grammyjs/types`); a test fails when it is out of date, and another when',
    "easytg itself calls a method the simulator doesn't answer. Other methods",
    "fail with `404 Not Found: the simulator doesn't support the method`.",
    '',
    `**${supported.size} of ${all.length}** methods are supported; ${
      planned.length
        ? `${planned.length} more are planned and ${unsupported.length - planned.length} are not planned.`
        : `the other ${unsupported.length} are not planned (new Bot API methods show up under "Planned").`
    }`,
    '',
    '## Supported',
    '',
    '| Area | Methods |',
    '|---|---|',
    ...[...areas].filter(([, methods]) => methods.length).map(([area, methods]) => `| ${area} (${methods.length}) | ${list(methods)} |`),
    '',
    '## Not supported',
    '',
    '### Planned',
    '',
    planned.length ? list(planned) : 'None.',
    '',
    '### Not planned (outside a UI library)',
    '',
    '| Group | Why | Methods |',
    '|---|---|---|',
    ...NOT_PLANNED.filter(([name]) => notPlanned.get(name)!.length).map(([name, why]) => `| ${name} | ${why} | ${list(notPlanned.get(name)!)} |`),
    '',
  ];
  return lines.join('\n');
}

if (import.meta.main) {
  writeFileSync(COVERAGE_PAGE, apiCoverage());
  console.log(`Wrote ${COVERAGE_PAGE}`);
}
